-- FastAPI-owned owner verification submissions for the bigint production schema.
-- Apply after 20261007_auth_identity_bridge.sql. No old RLS/client write path is removed.

BEGIN;

DO $$
BEGIN
    IF to_regprocedure('public.current_app_user_id()') IS NULL
       OR to_regprocedure('public.is_app_staff()') IS NULL THEN
        RAISE EXCEPTION 'owner-verification migration requires the identity bridge';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name = 'verification_status'
    ) THEN
        RAISE EXCEPTION 'owner-verification migration requires public.users.verification_status';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.owner_verification_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    submission_note text NOT NULL CHECK (
        char_length(btrim(submission_note)) BETWEEN 1 AND 4000
    ),
    status text NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVISION_REQUIRED')),
    review_note text CHECK (char_length(review_note) <= 1000),
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS owner_verification_created_at_idx
    ON public.owner_verification_applications (created_at DESC);

ALTER TABLE public.owner_verification_applications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.owner_verification_applications FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.owner_verification_applications TO authenticated;
DROP POLICY IF EXISTS owner_verification_read_self_or_staff
    ON public.owner_verification_applications;
CREATE POLICY owner_verification_read_self_or_staff
    ON public.owner_verification_applications FOR SELECT TO authenticated
    USING (user_id = public.current_app_user_id() OR public.is_app_staff());

-- A transaction-scoped marker lets the moderation RPC update the protected
-- profile fields. Clients cannot write this table or forge the marker via GUC.
CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC, anon;
GRANT USAGE ON SCHEMA app_private TO authenticated;
CREATE TABLE IF NOT EXISTS app_private.owner_verification_review_context (
    transaction_id bigint NOT NULL,
    auth_user_id uuid NOT NULL,
    target_user_id bigint NOT NULL,
    PRIMARY KEY (transaction_id, auth_user_id, target_user_id)
);
REVOKE ALL ON app_private.owner_verification_review_context FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION app_private.is_owner_verification_review_context(
    p_target_user_id bigint
)
RETURNS boolean
LANGUAGE sql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, app_private, auth
AS $$
    SELECT EXISTS (
        SELECT 1 FROM app_private.owner_verification_review_context AS marker
        WHERE marker.transaction_id = txid_current()
          AND marker.auth_user_id = auth.uid()
          AND marker.target_user_id = p_target_user_id
    )
$$;
REVOKE ALL ON FUNCTION app_private.is_owner_verification_review_context(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION app_private.is_owner_verification_review_context(bigint) TO authenticated;

-- The legacy trigger from 20261005 also clamps profile verification fields.
-- Give it the same narrowly scoped review-RPC exception before its normal guard.
CREATE OR REPLACE FUNCTION public.protect_user_columns()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, app_private
AS $$
BEGIN
    IF current_user NOT IN ('anon', 'authenticated') OR public.is_developer() THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'INSERT' THEN
        NEW.role := 'user';
        NEW.is_active := true;
        IF NEW.verification_status IS NOT NULL AND NEW.verification_status::text <> 'PENDING' THEN
            NEW.verification_status := NULL;
        END IF;
        NEW.catatan_revisi := NULL;
        RETURN NEW;
    END IF;

    IF app_private.is_owner_verification_review_context(OLD.id) THEN
        NEW.id := OLD.id;
        NEW.email := OLD.email;
        NEW.created_at := OLD.created_at;
        NEW.is_active := OLD.is_active;
        IF OLD.role::text IN ('developer', 'admin', 'moderator')
           OR NEW.role::text IN ('developer', 'admin', 'moderator') THEN
            NEW.role := OLD.role;
        END IF;
        IF NEW.verification_status::text NOT IN ('APPROVED', 'REJECTED', 'REVISION_REQUIRED') THEN
            NEW.verification_status := OLD.verification_status;
        END IF;
        IF NEW.verification_status::text <> 'REVISION_REQUIRED' THEN
            NEW.catatan_revisi := NULL;
        END IF;
        RETURN NEW;
    END IF;

    NEW.id := OLD.id;
    NEW.role := OLD.role;
    NEW.is_active := OLD.is_active;
    NEW.catatan_revisi := OLD.catatan_revisi;
    IF NEW.verification_status IS DISTINCT FROM OLD.verification_status THEN
        IF NEW.verification_status::text <> 'PENDING'
           OR COALESCE(OLD.verification_status::text, 'NONE') IN ('PENDING', 'APPROVED') THEN
            NEW.verification_status := OLD.verification_status;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

-- Keep the regular update guard intact. Only the SECURITY DEFINER RPC can set
-- this transaction-local flag, and only a non-client database role passes the
-- branch. A caller cannot bypass the guard by setting a custom GUC directly.
CREATE OR REPLACE FUNCTION public.protect_app_user_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF public.is_app_super_admin() THEN
        RETURN NEW;
    END IF;

    IF current_user NOT IN ('anon', 'authenticated')
       AND current_setting('app.owner_verification_rpc', true) = 'on' THEN
        NEW.id := OLD.id;
        NEW.email := OLD.email;
        NEW.auth_provider := OLD.auth_provider;
        NEW.created_at := OLD.created_at;
        NEW.role := OLD.role;
        NEW.is_active := OLD.is_active;
        NEW.catatan_revisi := OLD.catatan_revisi;
        IF NEW.verification_status::text <> 'PENDING'
           OR COALESCE(OLD.verification_status::text, 'NONE') IN ('PENDING', 'APPROVED') THEN
            NEW.verification_status := OLD.verification_status;
        END IF;
        RETURN NEW;
    END IF;

    IF app_private.is_owner_verification_review_context(OLD.id) THEN
        NEW.id := OLD.id;
        NEW.email := OLD.email;
        NEW.auth_provider := OLD.auth_provider;
        NEW.created_at := OLD.created_at;
        NEW.is_active := OLD.is_active;
        IF OLD.role::text IN ('developer', 'admin', 'moderator')
           OR NEW.role::text IN ('developer', 'admin', 'moderator') THEN
            NEW.role := OLD.role;
        END IF;
        IF NEW.verification_status::text NOT IN ('APPROVED', 'REJECTED', 'REVISION_REQUIRED') THEN
            NEW.verification_status := OLD.verification_status;
        END IF;
        IF NEW.verification_status::text <> 'REVISION_REQUIRED' THEN
            NEW.catatan_revisi := NULL;
        END IF;
        RETURN NEW;
    END IF;

    NEW.id := OLD.id;
    NEW.email := OLD.email;
    NEW.auth_provider := OLD.auth_provider;
    NEW.created_at := OLD.created_at;

    IF NOT public.is_app_staff() THEN
        NEW.role := OLD.role;
        NEW.is_active := OLD.is_active;
        NEW.verification_status := OLD.verification_status;
    ELSIF OLD.role::text IN ('developer', 'admin', 'moderator')
       OR NEW.role::text IN ('developer', 'admin', 'moderator') THEN
        NEW.role := OLD.role;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_owner_verification_application(
    p_submission_note text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    app_user_id bigint := public.current_app_user_id();
    app_role text;
    current_status text;
    active boolean;
    application_id bigint;
BEGIN
    IF app_user_id IS NULL THEN
        RAISE EXCEPTION 'identity link required' USING ERRCODE = '42501';
    END IF;
    IF p_submission_note IS NULL OR char_length(btrim(p_submission_note)) NOT BETWEEN 1 AND 4000 THEN
        RAISE EXCEPTION 'invalid application details' USING ERRCODE = '22023';
    END IF;

    SELECT role::text, verification_status::text, is_active
    INTO app_role, current_status, active
    FROM public.users
    WHERE id = app_user_id
    FOR UPDATE;

    IF NOT FOUND OR active IS DISTINCT FROM true
       OR app_role NOT IN ('user', 'owner')
       OR public.is_app_staff() THEN
        RAISE EXCEPTION 'account cannot submit an owner application' USING ERRCODE = '55000';
    END IF;
    IF COALESCE(current_status, 'NONE') NOT IN ('NONE', 'REJECTED', 'REVISION_REQUIRED') THEN
        RAISE EXCEPTION 'owner application already active' USING ERRCODE = '23505';
    END IF;

    PERFORM set_config('app.owner_verification_rpc', 'on', true);
    UPDATE public.users SET verification_status = 'PENDING' WHERE id = app_user_id;
    -- Do not let the transaction-local flag affect another profile update in
    -- the same transaction (for example, a subsequent moderation RPC).
    PERFORM set_config('app.owner_verification_rpc', 'off', true);

    UPDATE public.owner_verification_applications
    SET status = CASE
            WHEN current_status = 'REVISION_REQUIRED' THEN 'REVISION_REQUIRED'
            ELSE 'REJECTED'
        END,
        updated_at = now()
    WHERE user_id = app_user_id AND status = 'PENDING';

    INSERT INTO public.owner_verification_applications (user_id, submission_note)
    VALUES (app_user_id, btrim(p_submission_note))
    RETURNING id INTO application_id;

    RETURN application_id;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_owner_verification_application(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_owner_verification_application(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.review_owner_verification_application(
    p_application_id bigint,
    p_status text,
    p_review_note text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    reviewer_id bigint := public.current_app_user_id();
    review_target_user_id bigint;
    application_status text;
    updated_role text;
    updated_status text;
    note text := nullif(btrim(p_review_note), '');
BEGIN
    IF reviewer_id IS NULL OR NOT public.is_app_staff() THEN
        RAISE EXCEPTION 'staff access required' USING ERRCODE = '42501';
    END IF;
    IF p_status NOT IN ('APPROVED', 'REJECTED', 'REVISION_REQUIRED')
       OR char_length(COALESCE(note, '')) > 1000
       OR (p_status IN ('REJECTED', 'REVISION_REQUIRED') AND note IS NULL) THEN
        RAISE EXCEPTION 'invalid review decision' USING ERRCODE = '22023';
    END IF;

    SELECT user_id, status INTO review_target_user_id, application_status
    FROM public.owner_verification_applications
    WHERE id = p_application_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'application not found' USING ERRCODE = 'P0002';
    END IF;
    IF application_status <> 'PENDING' THEN
        RAISE EXCEPTION 'application already reviewed' USING ERRCODE = '23505';
    END IF;

    INSERT INTO app_private.owner_verification_review_context (
        transaction_id, auth_user_id, target_user_id
    ) VALUES (txid_current(), auth.uid(), review_target_user_id);
    IF NOT app_private.is_owner_verification_review_context(review_target_user_id) THEN
        RAISE EXCEPTION 'review context marker is not visible to the profile guards';
    END IF;
    UPDATE public.users
    SET verification_status = p_status,
        role = CASE WHEN p_status = 'APPROVED' THEN 'owner' ELSE role END,
        catatan_revisi = CASE WHEN p_status = 'REVISION_REQUIRED' THEN note ELSE NULL END
    WHERE id = review_target_user_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'applicant profile not found' USING ERRCODE = 'P0002';
    END IF;
    SELECT role::text, verification_status::text
    INTO updated_role, updated_status
    FROM public.users WHERE id = review_target_user_id;
    IF updated_status IS DISTINCT FROM p_status
       OR (p_status = 'APPROVED' AND updated_role IS DISTINCT FROM 'owner') THEN
        RAISE EXCEPTION 'profile guard rejected review: role %, status %, db role %, marker %, superadmin %',
            updated_role, updated_status, current_user,
            app_private.is_owner_verification_review_context(review_target_user_id),
            public.is_app_super_admin();
    END IF;
    DELETE FROM app_private.owner_verification_review_context AS marker
    WHERE marker.transaction_id = txid_current()
      AND marker.auth_user_id = auth.uid()
      AND marker.target_user_id = review_target_user_id;

    UPDATE public.owner_verification_applications
    SET status = p_status,
        review_note = note,
        reviewed_by = reviewer_id,
        reviewed_at = now(),
        updated_at = now()
    WHERE id = p_application_id;
END;
$$;

REVOKE ALL ON FUNCTION public.review_owner_verification_application(bigint, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_owner_verification_application(bigint, text, text) TO authenticated;

COMMIT;
