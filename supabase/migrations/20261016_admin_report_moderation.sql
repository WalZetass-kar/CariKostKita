-- Staff-only report decisions and an append-only moderation history.
-- Apply after 20261007_auth_identity_bridge.sql and 20261015_owner_verification_fastapi.sql.

BEGIN;

DO $$
BEGIN
    IF to_regprocedure('public.current_app_user_id()') IS NULL
       OR to_regprocedure('public.is_app_staff()') IS NULL
       OR to_regclass('public.reports') IS NULL
       OR to_regclass('app_private.owner_verification_review_context') IS NULL THEN
        RAISE EXCEPTION 'report moderation migration requires the identity bridge and owner-verification migration';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'reports' AND column_name = 'status'
    ) THEN
        RAISE EXCEPTION 'report moderation migration requires public.reports.status';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS app_private.report_moderation_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id bigint NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
    moderator_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    status text NOT NULL CHECK (status IN ('DITINJAU', 'SELESAI', 'DITOLAK')),
    action_note text CHECK (char_length(action_note) <= 1000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS report_moderation_actions_report_created_idx
    ON app_private.report_moderation_actions (report_id, created_at DESC);

ALTER TABLE app_private.report_moderation_actions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON app_private.report_moderation_actions FROM PUBLIC, anon, authenticated;
GRANT SELECT ON app_private.report_moderation_actions TO authenticated;
DROP POLICY IF EXISTS report_moderation_actions_staff_read
    ON app_private.report_moderation_actions;
CREATE POLICY report_moderation_actions_staff_read
    ON app_private.report_moderation_actions FOR SELECT TO authenticated
    USING (public.is_app_staff());

CREATE OR REPLACE FUNCTION public.review_kost_report(
    p_report_id bigint,
    p_status text,
    p_action_note text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, app_private
AS $$
DECLARE
    moderator_id bigint := public.current_app_user_id();
    current_status text;
    note text := nullif(btrim(p_action_note), '');
BEGIN
    IF moderator_id IS NULL OR NOT public.is_app_staff() THEN
        RAISE EXCEPTION 'staff access required' USING ERRCODE = '42501';
    END IF;
    IF p_status NOT IN ('DITINJAU', 'SELESAI', 'DITOLAK')
       OR char_length(COALESCE(note, '')) > 1000 THEN
        RAISE EXCEPTION 'invalid report decision' USING ERRCODE = '22023';
    END IF;

    SELECT status::text INTO current_status
    FROM public.reports WHERE id = p_report_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'report not found' USING ERRCODE = 'P0002';
    END IF;
    IF current_status IN ('SELESAI', 'DITOLAK') THEN
        RAISE EXCEPTION 'report is already final' USING ERRCODE = '23505';
    END IF;

    UPDATE public.reports SET status = p_status, updated_at = now()
    WHERE id = p_report_id;
    INSERT INTO app_private.report_moderation_actions (report_id, moderator_id, status, action_note)
    VALUES (p_report_id, moderator_id, p_status, note);
END;
$$;

REVOKE ALL ON FUNCTION public.review_kost_report(bigint, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.review_kost_report(bigint, text, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.list_report_moderation_actions(p_report_ids bigint[])
RETURNS TABLE(report_id bigint, status text, action_note text, created_at timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, app_private
AS $$
BEGIN
    IF public.current_app_user_id() IS NULL OR NOT public.is_app_staff() THEN
        RAISE EXCEPTION 'staff access required' USING ERRCODE = '42501';
    END IF;
    IF COALESCE(array_length(p_report_ids, 1), 0) > 100 THEN
        RAISE EXCEPTION 'too many report IDs' USING ERRCODE = '22023';
    END IF;

    RETURN QUERY
    SELECT DISTINCT ON (action.report_id)
        action.report_id, action.status, action.action_note, action.created_at
    FROM app_private.report_moderation_actions AS action
    WHERE action.report_id = ANY(COALESCE(p_report_ids, ARRAY[]::bigint[]))
    ORDER BY action.report_id, action.created_at DESC, action.id DESC;
END;
$$;

REVOKE ALL ON FUNCTION public.list_report_moderation_actions(bigint[]) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.list_report_moderation_actions(bigint[]) TO authenticated;

COMMIT;
