-- Staff-controlled role/status changes through one audited RPC.
-- Apply after 20261015_owner_verification_fastapi.sql (creates app_private).

BEGIN;

DO $$
BEGIN
    IF to_regprocedure('public.current_app_user_id()') IS NULL
       OR to_regprocedure('public.is_app_staff()') IS NULL
       OR to_regprocedure('public.is_app_super_admin()') IS NULL
       OR to_regclass('app_private.owner_verification_review_context') IS NULL THEN
        RAISE EXCEPTION 'admin user moderation migration requires the identity and private schemas';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'role'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'is_active'
    ) THEN
        RAISE EXCEPTION 'admin user moderation migration requires users.role and users.is_active';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS app_private.admin_user_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Keep historical IDs after account deletion; audit history must neither
    -- disappear with its target nor block deletion of the acting account.
    target_user_id bigint NOT NULL,
    actor_user_id bigint NOT NULL,
    action text NOT NULL CHECK (action IN ('ROLE_CHANGED', 'STATUS_CHANGED')),
    old_value text,
    new_value text,
    reason text CHECK (char_length(reason) <= 1000),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (target_user_id <> actor_user_id)
);
CREATE INDEX IF NOT EXISTS admin_user_actions_target_created_idx
    ON app_private.admin_user_actions (target_user_id, created_at DESC);

ALTER TABLE app_private.admin_user_actions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON app_private.admin_user_actions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE app_private.admin_user_actions_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT ON app_private.admin_user_actions TO authenticated;
DROP POLICY IF EXISTS admin_user_actions_staff_read ON app_private.admin_user_actions;
CREATE POLICY admin_user_actions_staff_read
    ON app_private.admin_user_actions FOR SELECT TO authenticated
    USING (public.is_app_staff());

CREATE OR REPLACE FUNCTION public.admin_moderate_user(
    p_target_user_id bigint,
    p_role text DEFAULT NULL,
    p_is_active boolean DEFAULT NULL,
    p_reason text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, app_private
AS $$
DECLARE
    actor_id bigint := public.current_app_user_id();
    target_role text;
    target_is_active boolean;
    role_type text;
    action_name text;
    old_value text;
    new_value text;
    reason text := nullif(btrim(p_reason), '');
BEGIN
    IF actor_id IS NULL OR NOT public.is_app_staff() THEN
        RAISE EXCEPTION 'staff access required' USING ERRCODE = '42501';
    END IF;
    IF p_target_user_id = actor_id THEN
        RAISE EXCEPTION 'self moderation is not allowed' USING ERRCODE = '42501';
    END IF;
    IF ((p_role IS NULL) = (p_is_active IS NULL))
       OR char_length(COALESCE(reason, '')) > 1000 THEN
        RAISE EXCEPTION 'exactly one supported user change is required' USING ERRCODE = '22023';
    END IF;

    SELECT role::text, is_active INTO target_role, target_is_active
    FROM public.users WHERE id = p_target_user_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'user not found' USING ERRCODE = 'P0002';
    END IF;
    IF target_role IN ('developer', 'admin', 'moderator') THEN
        RAISE EXCEPTION 'staff accounts cannot be moderated here' USING ERRCODE = '42501';
    END IF;

    IF p_role IS NOT NULL THEN
        IF NOT public.is_app_super_admin() THEN
            RAISE EXCEPTION 'only super admin may change user roles' USING ERRCODE = '42501';
        END IF;
        IF p_role NOT IN ('user', 'moderator') OR target_role NOT IN ('user', 'moderator') THEN
            RAISE EXCEPTION 'only user/moderator roles may be changed here' USING ERRCODE = '22023';
        END IF;
        SELECT format_type(attribute.atttypid, attribute.atttypmod)
        INTO role_type
        FROM pg_attribute AS attribute
        WHERE attribute.attrelid = 'public.users'::regclass
          AND attribute.attname = 'role'
          AND NOT attribute.attisdropped;
        EXECUTE format('UPDATE public.users SET role = $1::%s WHERE id = $2', role_type)
        USING p_role, p_target_user_id;
        action_name := 'ROLE_CHANGED';
        old_value := target_role;
        new_value := p_role;
    ELSE
        UPDATE public.users SET is_active = p_is_active WHERE id = p_target_user_id;
        action_name := 'STATUS_CHANGED';
        old_value := target_is_active::text;
        new_value := p_is_active::text;
    END IF;

    INSERT INTO app_private.admin_user_actions (
        target_user_id, actor_user_id, action, old_value, new_value, reason
    ) VALUES (p_target_user_id, actor_id, action_name, old_value, new_value, reason);
END;
$$;

REVOKE ALL ON FUNCTION public.admin_moderate_user(bigint, text, boolean, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_moderate_user(bigint, text, boolean, text) TO authenticated;

COMMIT;
