-- Activity log schema and RLS for the FastAPI adapter.
-- Apply after 20261007_auth_identity_bridge.sql. This migration is additive;
-- it does not remove the Android or Admin-Gue compatibility paths.

BEGIN;

DO $$
BEGIN
    IF to_regprocedure('public.current_app_user_id()') IS NULL
       OR to_regprocedure('public.is_app_staff()') IS NULL THEN
        RAISE EXCEPTION 'activity log migration requires the auth identity bridge';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name = 'id' AND data_type = 'bigint'
    ) THEN
        RAISE EXCEPTION 'activity log migration requires public.users.id bigint';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.activity_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Intentionally no FK: retain the audit row when the actor profile is removed.
    user_id bigint NOT NULL,
    actor_name text CHECK (char_length(actor_name) <= 120),
    action_type text NOT NULL CHECK (char_length(action_type) BETWEEN 1 AND 80),
    description text NOT NULL CHECK (char_length(description) BETWEEN 1 AND 1000),
    target_type text CHECK (char_length(target_type) <= 80),
    target_id text CHECK (char_length(target_id) <= 100),
    created_at timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE
    item record;
    actual_type text;
    identity_mode text;
    id_default text;
BEGIN
    FOR item IN
        SELECT * FROM (VALUES
            ('id', 'bigint'),
            ('user_id', 'bigint'),
            ('actor_name', 'text'),
            ('action_type', 'text'),
            ('description', 'text'),
            ('target_type', 'text'),
            ('target_id', 'text'),
            ('created_at', 'timestamp with time zone')
        ) AS required(column_name, expected_type)
    LOOP
        SELECT data_type INTO actual_type
        FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'activity_logs'
          AND column_name = item.column_name;
        IF actual_type IS NULL THEN
            RAISE EXCEPTION 'activity_logs preflight failed: public.activity_logs.% is missing',
                item.column_name;
        END IF;

        IF item.expected_type = 'text' AND actual_type NOT IN ('text', 'character varying') THEN
            RAISE EXCEPTION 'activity_logs preflight failed: public.activity_logs.% must be text-like (found %)',
                item.column_name, actual_type;
        ELSIF item.expected_type = 'timestamp with time zone' AND actual_type NOT IN ('timestamp with time zone', 'timestamp without time zone') THEN
            RAISE EXCEPTION 'activity_logs preflight failed: public.activity_logs.% must be a timestamp (found %)',
                item.column_name, actual_type;
        ELSIF item.expected_type = 'bigint' AND actual_type NOT IN ('bigint', 'integer') THEN
            RAISE EXCEPTION 'activity_logs preflight failed: public.activity_logs.% must be bigint (found %)',
                item.column_name, actual_type;
        END IF;
    END LOOP;

    SELECT is_identity, column_default INTO identity_mode, id_default
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'activity_logs' AND column_name = 'id';
    IF COALESCE(identity_mode, 'NO') <> 'YES'
       AND COALESCE(id_default, '') NOT LIKE 'nextval(%' THEN
        RAISE EXCEPTION 'activity_logs preflight failed: id must be generated by identity/sequence';
    END IF;
END;
$$;

ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.activity_logs FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.activity_logs TO authenticated;
GRANT INSERT (user_id, actor_name, action_type, description, target_type, target_id)
    ON TABLE public.activity_logs TO authenticated;

DO $$
DECLARE
    policy_row record;
    id_sequence text;
BEGIN
    -- Remove any old permissive UUID-era policies before installing bridge policies.
    FOR policy_row IN
        SELECT policyname FROM pg_policies
        WHERE schemaname = 'public' AND tablename = 'activity_logs'
    LOOP
        EXECUTE format('DROP POLICY %I ON public.activity_logs', policy_row.policyname);
    END LOOP;

    id_sequence := pg_get_serial_sequence('public.activity_logs', 'id');
    IF id_sequence IS NULL THEN
        RAISE EXCEPTION 'activity_logs preflight failed: id sequence was not found';
    END IF;
    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', id_sequence);
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', id_sequence);
END;
$$;

CREATE POLICY activity_logs_select_own_or_staff
    ON public.activity_logs FOR SELECT TO authenticated
    USING (user_id = public.current_app_user_id() OR public.is_app_staff());

CREATE POLICY activity_logs_insert_self
    ON public.activity_logs FOR INSERT TO authenticated
    WITH CHECK (user_id = public.current_app_user_id());

COMMENT ON TABLE public.activity_logs IS
    'Append-only activity records; actor identity is the bridged bigint users.id and visibility is RLS-scoped.';
COMMENT ON COLUMN public.activity_logs.actor_name IS
    'Untrusted display-only label; never used for identity or authorization.';

COMMIT;
