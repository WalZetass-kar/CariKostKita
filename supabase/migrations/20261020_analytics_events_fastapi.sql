-- Requires 20261007_auth_identity_bridge.sql first.
-- Align analytics ingestion and admin aggregate reads to the verified bigint user ID.
-- Review production policies before applying; this migration is not auto-applied.

BEGIN;

CREATE TABLE IF NOT EXISTS public.app_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint,
    kost_id bigint,
    event text NOT NULL,
    metadata jsonb DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE
    item record;
    actual_type text;
    nullable_mode text;
    id_default text;
    id_identity text;
BEGIN
    IF to_regclass('public.app_events') IS NULL
       OR to_regprocedure('public.current_app_user_id()') IS NULL
       OR to_regprocedure('public.current_app_role()') IS NULL THEN
        RAISE EXCEPTION 'Analytics migration requires app_events and the identity bridge';
    END IF;

    FOR item IN
        SELECT * FROM (VALUES
            ('id', 'bigint'),
            ('user_id', 'bigint')
        ) AS required(column_name, expected_type)
    LOOP
        SELECT data_type INTO actual_type
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'app_events'
          AND column_name = item.column_name;
        IF actual_type IS NULL THEN
            RAISE EXCEPTION 'Analytics preflight failed: public.app_events.% is missing', item.column_name;
        ELSIF item.expected_type = 'bigint' AND actual_type NOT IN ('bigint', 'integer') THEN
            RAISE EXCEPTION 'Analytics preflight failed: public.app_events.% must be bigint (found %)',
                item.column_name, actual_type;
        END IF;
    END LOOP;

    SELECT is_nullable INTO nullable_mode
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'app_events' AND column_name = 'user_id';
    IF nullable_mode IS DISTINCT FROM 'YES' THEN
        RAISE EXCEPTION 'Analytics preflight failed: app_events.user_id must allow NULL for guest events';
    END IF;

    SELECT data_type INTO actual_type
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'app_events' AND column_name = 'event';
    IF actual_type IS NULL OR actual_type NOT IN ('text', 'character varying') THEN
        RAISE EXCEPTION 'Analytics preflight failed: public.app_events.event must be text-like (found %)',
            COALESCE(actual_type, 'missing');
    END IF;

    SELECT data_type INTO actual_type
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'app_events' AND column_name = 'created_at';
    IF actual_type IS NULL OR actual_type NOT IN ('timestamp with time zone', 'timestamp without time zone') THEN
        RAISE EXCEPTION 'Analytics preflight failed: public.app_events.created_at must be a timestamp (found %)',
            COALESCE(actual_type, 'missing');
    END IF;

    FOR item IN
        SELECT column_name FROM (VALUES ('kost_id'), ('created_at')) AS optional_fields(column_name)
    LOOP
        SELECT is_nullable, column_default INTO nullable_mode, id_default
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'app_events'
          AND column_name = item.column_name;
        IF nullable_mode IS NULL
           OR (nullable_mode <> 'YES' AND id_default IS NULL) THEN
            RAISE EXCEPTION 'Analytics preflight failed: app_events.% must be nullable or have a default',
                item.column_name;
        END IF;
    END LOOP;

    SELECT column_default, is_identity INTO id_default, id_identity
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'app_events' AND column_name = 'id';
    IF COALESCE(id_identity, 'NO') <> 'YES'
       AND COALESCE(id_default, '') NOT LIKE 'nextval(%' THEN
        RAISE EXCEPTION 'Analytics preflight failed: public.app_events.id must have an identity/sequence default';
    END IF;
END;
$$;

ALTER TABLE public.app_events ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    policy_row record;
BEGIN
    FOR policy_row IN
        SELECT policyname FROM pg_policies
        WHERE schemaname = 'public' AND tablename = 'app_events'
    LOOP
        EXECUTE format('DROP POLICY %I ON public.app_events', policy_row.policyname);
    END LOOP;
END;
$$;

REVOKE ALL ON TABLE public.app_events FROM PUBLIC, anon, authenticated;
GRANT INSERT ON TABLE public.app_events TO anon, authenticated;
GRANT SELECT ON TABLE public.app_events TO authenticated;
DO $$
DECLARE
    sequence_name text := pg_get_serial_sequence('public.app_events', 'id');
BEGIN
    IF sequence_name IS NOT NULL THEN
        EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', sequence_name);
        EXECUTE format('GRANT USAGE ON SEQUENCE %s TO anon, authenticated', sequence_name);
    END IF;
END;
$$;

CREATE POLICY app_events_insert_guest ON public.app_events
FOR INSERT TO anon
WITH CHECK (user_id IS NULL);

CREATE POLICY app_events_insert_authenticated ON public.app_events
FOR INSERT TO authenticated
WITH CHECK (user_id = public.current_app_user_id());

CREATE POLICY app_events_select_admin ON public.app_events
FOR SELECT TO authenticated
USING (public.current_app_role() IN ('developer', 'admin'));

COMMIT;
